PROXY = "http://127.0.0.1:10809"
ROUTE = fix.route_for(PROXY)


class BasicTests(unittest.TestCase):
    def test_proxy_validation(self):
        for url in (PROXY, "socks5h://[::1]:1080", "https://localhost:8443"):
            self.assertTrue(fix.valid_proxy(url), url)
        for url in ("DIRECT_TUN", "http://127.0.0.1", "http://remote:1080",
                    "http://user:secret@127.0.0.1:8080", "file:///etc/passwd",
                    "http://127.0.0.1:99999", "http://127.0.0.1:80\n", "http://127.0.0.1:80?x=y"):
            self.assertFalse(fix.valid_proxy(url), url)

    def test_direct_clears_all_proxy_variables(self):
        current = {**ROUTE, "SSL_CERT_FILE": "/custom/ca.pem", "TERM": "xterm"}
        self.assertEqual(fix.with_route(current, {}), {"SSL_CERT_FILE": "/custom/ca.pem", "TERM": "xterm"})

    def test_do_not_persist_credentials(self):
        self.assertIsNone(fix.persistent_route({"HTTPS_PROXY": "http://u:p@127.0.0.1:8080"}))

    def test_shell_update_is_idempotent(self):
        original = "# personal\nexport EDITOR=vim\n"
        commands = {"code": Path("/home/person with spaces/bin/code")}
        first = fix.shell_config(original, commands)
        self.assertEqual(first, fix.shell_config(first, commands))
        self.assertIn('export EDITOR=vim', first)

    def test_old_generated_alias_only_is_migrated(self):
        original = "alias ls='ls --color'\n# --- AUTO-GENERATED BY CODEX DOCTOR ---\nalias codex='HTTP_PROXY=bad codex'\n"
        updated = fix.shell_config(original, {"codex": Path("/managed/codex")})
        self.assertIn("alias ls=", updated)
        self.assertNotIn("HTTP_PROXY=bad", updated)

    def test_user_alias_and_broken_block_are_not_overwritten(self):
        for text in ("alias codex='custom'\n", fix.BEGIN + "\n", "codex() { echo custom; }\n",
                     "function codex { echo custom; }\n", fix.END + "\n" + fix.BEGIN):
            with self.assertRaises(ValueError):
                fix.shell_config(text, {"codex": Path("/managed/codex")})

    def test_desktop_classification(self):
        self.assertEqual(fix.desktop_kind("[Desktop Entry]\nExec=/usr/share/code/code %F\n"), "code")
        self.assertEqual(fix.desktop_kind("[Desktop Entry]\nExec=chatgpt %U\n"), "desktop")
        self.assertIsNone(fix.desktop_kind("Exec=/usr/bin/google-chrome --app=https://chatgpt.com\n"))
        self.assertEqual(fix.desktop_kind("Name=Codex\nExec=flatpak run com.example.Codex\n"), "unsupported")

    def test_port_discovery_ipv6_and_protocols(self):
        output = '\n'.join([
            'LISTEN 0 128 127.0.0.1:7890 0.0.0.0:*',
            'LISTEN 0 128 [::1]:2090 [::]:* users:(("sing-box",pid=3,fd=4))',
            'LISTEN 0 128 192.168.0.5:7890 0.0.0.0:*',
            'LISTEN 0 128 127.0.0.1:1455 0.0.0.0:* users:(("codex",pid=9,fd=1))',
        ])
        with patch.object(fix.shutil, "which", return_value="/usr/bin/ss"), patch.object(fix, "run", return_value=subprocess.CompletedProcess([], 0, output, "")):
            found = fix.discover_proxies()
        self.assertEqual(len(found), 4)
        self.assertIn("http://127.0.0.1:7890", found)
        self.assertIn("socks5h://[::1]:2090", found)


class ProbeTests(unittest.TestCase):
    def result(self, status, content="application/json", code=0):
        return subprocess.CompletedProcess([], code, f"{status} {content}", "")

    def test_final_http_status_and_content_type(self):
        probe = fix.Probe({})
        item = fix.ENDPOINTS[1]
        for status, mime, code, expected in [
            (401, "application/json", 0, True), (403, "application/json", 0, False),
            (401, "text/html", 0, False), (200, "application/json", 0, False),
            (401, "application/json", 60, False), (503, "text/html", 0, False),
        ]:
            with patch.object(fix, "run", return_value=self.result(status, mime, code)):
                self.assertEqual(probe.endpoint(item, {})[1], expected)

    def test_curl_no_rc_and_no_tls_bypass(self):
        with patch.object(fix, "run", return_value=self.result(401)) as mocked:
            fix.Probe(ROUTE).endpoint(fix.ENDPOINTS[1], {})
        argv = mocked.call_args.args[0]
        self.assertEqual(argv[:2], ["curl", "-q"])
        self.assertNotIn("--insecure", argv)
        self.assertFalse(any(k in mocked.call_args.kwargs["env"] for k in fix.PROXY_KEYS))

    def test_cache_and_fresh_check(self):
        with patch.object(fix.Probe, "endpoint", return_value=("x", True, "HTTP 401")) as mocked:
            probe = fix.Probe({})
            self.assertTrue(probe.check({})[0])
            probe.check({})
            self.assertEqual(mocked.call_count, 3)
            probe.check({}, fresh=True)
            self.assertEqual(mocked.call_count, 6)


class FilesTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="codex-fix-test-")
        self.addCleanup(self.temp.cleanup)
        self.home = Path(self.temp.name)
        self.store = fix.Store(self.home)

    def test_apply_repeat_and_restore_first_original(self):
        path = self.home / ".bashrc"
        path.write_text("original\n")
        path.chmod(0o640)
        self.assertEqual(self.store.apply({path: (b"first\n", 0o640)}, {"codex": ROUTE}), 1)
        stamp = path.stat().st_mtime_ns
        self.assertEqual(self.store.apply({path: (b"first\n", 0o640)}, {}), 0)
        self.assertEqual(stamp, path.stat().st_mtime_ns)
        self.store.apply({path: (b"second\n", 0o640)}, {"codex": {}})
        self.assertEqual(stat.S_IMODE(self.store.manifest.stat().st_mode), 0o600)
        self.store.restore()
        self.assertEqual(path.read_text(), "original\n")
        self.assertEqual(stat.S_IMODE(path.stat().st_mode), 0o640)

    def test_restore_removes_only_own_created_file(self):
        path = self.store.bin / "codex"
        unrelated = self.home / "keep.txt"
        unrelated.write_text("keep")
        self.store.apply({path: (b"test", 0o700)}, {})
        self.store.restore()
        self.assertFalse(path.exists())
        self.assertEqual(unrelated.read_text(), "keep")

    def test_manual_edit_blocks_repair_and_restore(self):
        path = self.home / "managed"
        self.store.apply({path: (b"initial", 0o600)}, {})
        path.write_text("user's changes")
        with self.assertRaises(ValueError):
            self.store.apply({path: (b"new", 0o600)}, {})
        with self.assertRaises(ValueError):
            self.store.restore()
        self.assertEqual(path.read_text(), "user's changes")

    def test_symlinks_and_outside_paths_rejected(self):
        target = self.home / "real"
        target.write_text("real")
        link = self.home / "link"
        link.symlink_to(target)
        for path in (link, self.home / ".." / "escape"):
            with self.assertRaises(ValueError):
                self.store.apply({path: (b"replace", 0o600)}, {})

    def test_corrupted_manifest_is_rejected(self):
        self.store.root.mkdir(parents=True)
        for value in ([], {"version": 2}, {"version": 2, "files": {}, "routes": {"x": {"bad;key": "value"}}}):
            self.store.manifest.write_text(json.dumps(value))
            with self.assertRaises(ValueError):
                fix.Store(self.home)

    def test_failure_rolls_back_already_written_files(self):
        one, two = self.home / "one", self.home / "two"
        one.write_text("old")
        real_write = fix.atomic_write

        def fail(path, data, mode):
            if path == two:
                raise OSError("simulated disk failure")
            real_write(path, data, mode)

        with patch.object(fix, "atomic_write", side_effect=fail):
            with self.assertRaises(OSError):
                self.store.apply({one: (b"new", 0o600), two: (b"new", 0o600)}, {})
        self.assertEqual(one.read_text(), "old")
        self.assertFalse(two.exists())
        self.assertFalse(self.store.manifest.exists())

    def test_wrapper_preserves_arguments_and_direct_clears_bad_proxy(self):
        binary = self.home / "fake program"
        binary.write_text('#!/usr/bin/env python3\nimport os, sys, json\nprint(json.dumps([sys.argv[1:], os.environ.get("HTTPS_PROXY")]))\n')
        binary.chmod(0o700)
        path = self.home / "wrapper"
        path.write_text(fix.wrapper(binary, {}))
        path.chmod(0o700)
        result = subprocess.run([str(path), "with spaces", "$(false)", "quote'"],
                                env={**os.environ, **ROUTE}, capture_output=True, text=True, check=True)
        self.assertEqual(json.loads(result.stdout), [["with spaces", "$(false)", "quote'"], None])

    def test_wrapper_in_path_is_not_wrapped_recursively(self):
        binary = self.home / "real-codex"
        binary.write_text("#!/bin/sh\nexit 0\n")
        path = self.home / "codex"
        path.write_text(fix.wrapper(binary, ROUTE))
        with patch.object(fix.shutil, "which", side_effect=lambda name: str(path) if name == "codex" else None):
            self.assertEqual(fix.installed_targets()[0].command, str(binary))
        path.write_text(fix.wrapper(path, ROUTE))
        with patch.object(fix.shutil, "which", side_effect=lambda name: str(path) if name == "codex" else None):
            with self.assertRaises(ValueError):
                fix.installed_targets()

    def test_desktop_patch_idempotent_and_preserves_actions(self):
        binary = self.home / "fake-code"
        binary.write_text("#!/bin/sh\nexit 0\n")
        binary.chmod(0o700)
        original = f'[Desktop Entry]\nName=VS Code\nType=Application\nDBusActivatable=true\nExec="{binary}" %F\nActions=new;\n\n[Desktop Action new]\nName=New\nExec="{binary}" --new-window %F\n'
        result, writes = fix.desktop_patch(original, ROUTE, self.store.bin, "code.desktop")
        again, second_writes = fix.desktop_patch(result, ROUTE, self.store.bin, "code.desktop")
        self.assertEqual(result, again)
        self.assertEqual(writes, second_writes)
        self.assertIn("DBusActivatable=false", result)
        self.assertIn(" --new-window %F", result)
        self.assertEqual(len(writes), 2)
        if shutil.which("desktop-file-validate"):
            desktop = self.home / "code.desktop"
            desktop.write_text(result)
            completed = subprocess.run(["desktop-file-validate", str(desktop)], capture_output=True, text=True)
            self.assertEqual(completed.returncode, 0, completed.stdout + completed.stderr)


class CliTests(unittest.TestCase):
    def test_fix_selects_automatic_repair(self):
        with patch.object(fix.os, "geteuid", return_value=1000), patch.object(fix.socket, "socket"), patch.object(fix, "doctor", return_value=0) as doctor:
            self.assertEqual(fix.main(["--fix"]), 0)
        args = doctor.call_args.args[0]
        self.assertTrue(args.fix)
        self.assertFalse(args.check)
        self.assertFalse(args.restore)

    def test_fix_rejects_conflicting_modes_before_repair(self):
        for flag in ("--check", "--dry-run", "--restore"):
            with contextlib.redirect_stderr(io.StringIO()), patch.object(fix, "doctor") as doctor:
                with self.assertRaises(SystemExit) as error:
                    fix.main(["--fix", flag])
                self.assertEqual(error.exception.code, 2)
                doctor.assert_not_called()


class DoctorTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="codex-fix-doctor-")
        self.addCleanup(self.temp.cleanup)
        self.home = Path(self.temp.name)
        self.args = argparse.Namespace(restore=False, check=False, proxy=None, timeout=1)
        self.stack = contextlib.ExitStack()
        self.addCleanup(self.stack.close)
        self.stack.enter_context(contextlib.redirect_stdout(io.StringIO()))
        self.stack.enter_context(patch.object(fix, "process_environments", return_value={}))
        self.stack.enter_context(patch.object(fix, "desktop_files", return_value={}))
        self.stack.enter_context(patch.object(fix, "installed_targets", return_value=[fix.Target("codex", "/usr/bin/codex")]))
        self.stack.enter_context(patch.object(fix, "discover_proxies", return_value=[PROXY]))

    def test_healthy_run_creates_no_files(self):
        with patch.object(fix.Probe, "check", return_value=(True, "healthy")):
            self.assertEqual(fix.doctor(self.args, home=self.home, env={}), 0)
        self.assertEqual(list(self.home.iterdir()), [])

    def test_check_and_no_route_create_no_files(self):
        self.args.check = True
        with patch.object(fix.Probe, "check", side_effect=lambda route, **kw: (bool(route), "probe")):
            self.assertEqual(fix.doctor(self.args, home=self.home, env={}), 3)
        self.assertEqual(list(self.home.iterdir()), [])
        self.args.check = False
        with patch.object(fix.Probe, "check", return_value=(False, "blocked")):
            with self.assertRaises(ValueError):
                fix.doctor(self.args, home=self.home, env={})
        self.assertEqual(list(self.home.iterdir()), [])

    def test_fix_then_noop_then_direct_recovery(self):
        with patch.object(fix.Probe, "check", side_effect=lambda route, **kw: (bool(route), "probe")):
            self.assertEqual(fix.doctor(self.args, home=self.home, env={}), 0)
            before = {p: (p.read_bytes(), p.stat().st_mtime_ns) for p in self.home.rglob("*") if p.is_file()}
            self.assertEqual(fix.doctor(self.args, home=self.home, env={}), 0)
            after = {p: (p.read_bytes(), p.stat().st_mtime_ns) for p in self.home.rglob("*") if p.is_file()}
            self.assertEqual(before, after)
        with patch.object(fix.Probe, "check", side_effect=lambda route, **kw: (not route, "direct only")):
            self.assertEqual(fix.doctor(self.args, home=self.home, env={}), 0)
        self.assertNotIn(PROXY, (self.home / ".local/share/codex-fix/bin/codex").read_text())

    def test_working_cli_untouched_when_gui_needs_repair(self):
        targets = [fix.Target("codex", "/usr/bin/codex"), fix.Target("code", "/usr/bin/code", True), fix.Target("chatgpt", "/usr/bin/chatgpt", True)]
        with patch.object(fix, "installed_targets", return_value=targets), patch.object(fix.Probe, "check", side_effect=lambda route, **kw: (bool(route), "probe")):
            self.assertEqual(fix.doctor(self.args, home=self.home, env=ROUTE), 0)
        self.assertFalse((self.home / ".local/share/codex-fix/bin/codex").exists())
        self.assertTrue((self.home / ".local/share/codex-fix/bin/code").exists())
        self.assertTrue((self.home / ".local/share/codex-fix/bin/chatgpt").exists())

    def test_failed_recheck_aborts_before_writes(self):
        with patch.object(fix.Probe, "check", side_effect=lambda route, **kw: (bool(route) and not kw.get("fresh"), "probe")):
            with self.assertRaises(ValueError):
                fix.doctor(self.args, home=self.home, env={})
        self.assertEqual(list(self.home.iterdir()), [])

    def test_editor_custom_override_reports_partial_status(self):
        settings = self.home / ".config/Code/User/settings.json"
        settings.parent.mkdir(parents=True)
        text = '{"chatgpt.cliExecutable": "/custom/codex"}\n'
        settings.write_text(text)
        with patch.object(fix.Probe, "check", return_value=(True, "healthy")):
            self.assertEqual(fix.doctor(self.args, home=self.home, env={}), 1)
        self.assertEqual(settings.read_text(), text)


